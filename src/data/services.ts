/** Service offerings rendered in the Services section. */

export interface Service {
  id: string;
  index: string;
  title: string;
  /**
   * Обещание направления одной строкой: что изменится у заказчика.
   * Стоит сразу под названием - до цены человек решает, про него ли это
   * вообще. Прежний текст описывал нас («встраиваем интеллект», «полный
   * цикл»), а не его результат.
   */
  outcome: string;
  /** Что входит в работу - результатами, а не названиями этапов. */
  capabilities: string[];
  /**
   * Срок до запуска - второй вопрос после цены, и отсутствие ответа на
   * него человек достраивает худшим вариантом.
   *
   * TODO: сверить с реальной загрузкой команды. Значения поставлены
   * по здравому смыслу и должны быть подтверждены до публикации.
   */
  timeline?: string;
  /** Display price - "от …" for project work, "По подписке" for Larkins. */
  price: string;
  /**
   * Чем направление уже подтверждено. Только проверяемые факты: кейсы из
   * портфолио и то, что работает на этом сайте. Цифр, которых у нас нет,
   * здесь не появляется.
   */
  trust?: string;
  /**
   * Действие карточки. Без него человек, выбравший направление, вынужден
   * искать форму сам - а он уже сказал, о чём хочет говорить.
   */
  cta: string;
  /** Ссылка вместо формы. Есть только у Larkins: у него своя страница. */
  href?: string;
  /** Larkins gets a distinct, almost-released treatment. */
  featured?: boolean;
  status?: string;
}

