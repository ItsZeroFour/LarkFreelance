/**
 * Тема обращения: связывает карточку услуги с формой заявки.
 *
 * Человек, нажавший «Обсудить автоматизацию», уже сказал, что ему нужно.
 * Заставлять его повторять это в разговоре - терять то, что он сообщил
 * бесплатно, поэтому выбранное направление доезжает до формы, показывается
 * в ней и уходит команде вместе с номером.
 *
 * Передаём событием, а не параметром в адресе: услуги и форма живут на одной
 * странице, якорь `#contact` уже листает до формы, и городить поверх этого
 * маршрутизацию незачем.
 */

export const LEAD_TOPIC_EVENT = "lark:lead-topic";

export interface LeadTopic {
  /** Стабильный идентификатор - уходит в уведомление команде. */
  id: string;
  /** Человеческое имя темы - показывается в форме. */
  label: string;
}

/** Сообщить форме заявки, о чём хочет говорить человек. */
export function requestLeadTopic(topic: LeadTopic): void {
  if (typeof window === "undefined") return;
  window.dispatchEvent(
    new CustomEvent<LeadTopic>(LEAD_TOPIC_EVENT, { detail: topic }),
  );
}
